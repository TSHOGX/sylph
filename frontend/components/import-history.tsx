"use client";

import { useEffect, useId, useRef, useState } from "react";
import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { importsApi, type ImportMode } from "@/lib/imports-api";
import type { Session } from "@/lib/api";
import { createSubmissionIdentity } from "@/lib/submission-identity";
import { useT } from "@/lib/i18n";
import { Button, IconButton } from "@/components/ui/button";
import { XIcon, RefreshIcon } from "@/components/icons";

interface ImportHistoryProps {
  environment: string;
  workdir?: string;
  autoStartKey?: string;
  onClose?: () => void;
}

export function ImportHistory(props: ImportHistoryProps) {
  return <ScopedImportHistory key={JSON.stringify([props.environment, props.workdir])} {...props} />;
}

function ScopedImportHistory({ environment, workdir, autoStartKey, onClose }: ImportHistoryProps) {
  const client = useQueryClient();
  const t = useT();
  const modeId = useId();
  const [submissionIdentity] = useState(createSubmissionIdentity);
  const [draftMode, setDraftMode] = useState<ImportMode>();
  const [selectedId, setSelectedId] = useState<string | null>(null);
  const [cursor, setCursor] = useState<number | undefined>();
  const autoStarted = useRef(false);
  const unfinishedJobs = useRef(new Set<string>());
  const recent = useQuery({ queryKey: ["imports", environment, workdir], queryFn: ({ signal }) => importsApi.list(environment, workdir, signal) });
  const jobId = selectedId ?? recent.data?.jobs[0]?.id;
  const current = useQuery({
    queryKey: ["import", jobId], queryFn: ({ signal }) => importsApi.get(jobId!, signal), enabled: Boolean(jobId),
    // Progress is durable server state. A two-second cadence keeps the panel
    // responsive while avoiding one request per second for every open workspace.
    refetchInterval: (query) => ["queued", "running"].includes(query.state.data?.job.status ?? "") ? 2000 : false,
  });
  const job = current.data?.job ?? recent.data?.jobs.find((entry) => entry.id === jobId);
  const active = job?.status === "queued" || job?.status === "running";
  const terminalStatus = active ? null : job?.status;
  const items = useQuery({
    queryKey: ["import-items", jobId, cursor],
    queryFn: ({ signal }) => importsApi.items(jobId!, cursor, signal),
    enabled: Boolean(jobId),
    // Item rows are detail, not the progress signal. Polling them every second
    // doubled the traffic generated by each open import panel and competed with
    // the work the import itself needs to do.
    refetchInterval: active ? 5000 : false,
  });
  const create = useMutation({
    mutationFn: async (request: { mode: ImportMode; idempotencyKey: string }) => {
      const response = await importsApi.create(environment, { workdir, ...request });
      submissionIdentity.accepted(request.idempotencyKey);
      return response;
    },
    onSuccess: ({ job }) => {
      unfinishedJobs.current.add(job.id);
      setSelectedId(job.id);
      setDraftMode(undefined);
      setCursor(undefined);
      client.setQueryData(["import", job.id], { job });
      void recent.refetch();
    },
  });
  // A running job can have been accepted earlier by another panel. Its server
  // mode outranks the next-run draft; a pending POST shows its own snapshot.
  const mode = create.isPending ? create.variables.mode : active ? job!.mode : draftMode ?? job?.mode ?? "import_once";
  const loadingMode = recent.isPending || (Boolean(jobId) && !job);
  const mutate = create.mutate;
  useEffect(() => {
    if (autoStartKey && !loadingMode && !autoStarted.current) {
      autoStarted.current = true;
      mutate({ mode, idempotencyKey: submissionIdentity.key({ environment, workdir, mode }, autoStartKey) });
    }
  }, [autoStartKey, environment, loadingMode, mode, mutate, submissionIdentity, workdir]);
  useEffect(() => {
    if (!jobId) return;
    if (!terminalStatus) {
      unfinishedJobs.current.add(jobId);
      return;
    }
    // Opening Settings can mount many completed jobs. Only newly accepted or
    // observed running jobs invalidate records when they finish.
    if (!unfinishedJobs.current.delete(jobId)) return;
    void client.invalidateQueries({ queryKey: ["sessions"] });
    void client.invalidateQueries({ queryKey: ["workspaces"] });
    void client.invalidateQueries({ queryKey: ["import-items", jobId] });
    void client.invalidateQueries({
      predicate: (query) => {
        const [resource, sessionId] = query.queryKey;
        if ((resource !== "session" && resource !== "files") || typeof sessionId !== "string") return false;
        const session = client.getQueryData<{ session: Session }>(["session", sessionId])?.session;
        return !session || (session.environment === environment && (!workdir || session.workdir === workdir));
      },
    });
  }, [client, environment, workdir, jobId, terminalStatus]);
  const change = useMutation({
    mutationFn: (action: "cancel" | "retry") => importsApi[action](jobId!),
    onSuccess: ({ job }) => { unfinishedJobs.current.add(job.id); client.setQueryData(["import", job.id], { job }); void items.refetch(); },
  });
  const error = create.error ?? change.error ?? current.error ?? recent.error ?? items.error;
  return (
    <div className="w-full min-w-0 max-w-full space-y-2 overflow-hidden border-t border-line px-2 pt-2 text-xs">
      <div className="flex items-center gap-2">
        <h3 className="min-w-0 flex-1 truncate font-semibold">{workdir ? "Workspace history" : "Import all history"}</h3>
        {onClose && <IconButton label="Close history import" onClick={onClose}><XIcon size={14} /></IconButton>}
      </div>
      {workdir && <p className="truncate text-2xs text-ink-muted" title={workdir}>{workdir}</p>}
      <fieldset aria-describedby={`${modeId}-hint`} className="flex min-w-0 flex-wrap gap-x-3 gap-y-1" disabled={active || create.isPending}>
        <legend className="sr-only">History synchronization mode</legend>
        <label className="flex items-center gap-1"><input type="radio" name={modeId} checked={mode === "import_once"} onChange={() => setDraftMode("import_once")} />Import once</label>
        <label className="flex items-center gap-1"><input type="radio" name={modeId} checked={mode === "import_and_watch"} onChange={() => setDraftMode("import_and_watch")} />Import and keep syncing</label>
      </fieldset>
      <p id={`${modeId}-hint`} className="text-2xs leading-relaxed text-ink-muted">
        {active || create.isPending ? t("imports.modeLocked") : t("imports.modeHint")}
      </p>
      <div className="flex flex-wrap items-center gap-2">
        <Button onClick={() => create.mutate({ mode, idempotencyKey: submissionIdentity.key({ environment, workdir, mode }) })} disabled={loadingMode || active || create.isPending}>
          <RefreshIcon size={12} />{workdir ? "Sync history now" : "Import all history"}
        </Button>
        {active && <Button variant="ghost" onClick={() => change.mutate("cancel")} disabled={change.isPending || job?.cancelRequested}>Cancel</Button>}
        {job && !active && (job.failed > 0 || job.status === "failed" || job.status === "cancelled") && <Button variant="ghost" onClick={() => change.mutate("retry")} disabled={change.isPending}>Retry remaining</Button>}
      </div>
      {error && <p role="alert" className="break-words text-danger">{error.message}</p>}
      {job && <>
        <output className="block text-2xs text-ink-soft" aria-live="polite">
          {job.cancelRequested && active ? "Cancelling" : job.status === "running" && !job.scanComplete ? "Discovering history" : job.status}
          {` · ${job.imported} imported · ${job.refreshed} refreshed · ${job.skipped} skipped · ${job.failed} failed`}
        </output>
        {active && <progress className="block h-1.5 w-full max-w-full overflow-hidden rounded" max={Math.max(job.total, 1)} value={job.scanComplete ? job.total - job.pending : undefined} aria-label={t("imports.progress")} />}
        {job.error && <p role="alert" className="break-words text-danger">{job.error}</p>}
        {items.data && items.data.items.length > 0 && <ul className="max-h-48 overflow-y-auto divide-y divide-line">
          {items.data.items.map((item) => <li key={`${item.agent}:${item.nativeId}`} className="py-1">
            <div className="flex min-w-0 items-baseline gap-2"><span className="min-w-0 flex-1 truncate">{item.title ?? item.nativeId}</span><span className="shrink-0 text-3xs text-ink-muted">{item.status}</span></div>
            {item.reason && <p className="break-words text-3xs text-danger">{item.reason}</p>}
          </li>)}
        </ul>}
        {(cursor !== undefined || items.data?.nextCursor != null) && <div className="flex gap-2">
          {cursor !== undefined && <Button variant="ghost" onClick={() => setCursor(undefined)}>First page</Button>}
          {items.data?.nextCursor != null && <Button variant="ghost" onClick={() => setCursor(items.data!.nextCursor!)}>Next page</Button>}
        </div>}
      </>}
    </div>
  );
}
