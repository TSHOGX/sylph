-- Who started a turn.
--
-- Every turn used to be a user's: one row per POST, created before the agent was
-- told anything. That made "no turn is running" mean "the agent has nothing to say",
-- and events arriving outside a turn were dropped for having nowhere to belong.
--
-- Measured against claude 2.x, that is false. After a turn's `result`, a session
-- with backgrounded work emits `background_tasks_changed`, `task_updated`, and
-- `task_notification` when that work finishes — and then opens an entire exchange of
-- its own (`init`, `assistant`, `result`) to report it. Its stdout stays open and the
-- process does not exit. So an agent speaks unprompted, and the drop discarded
-- exactly the completion a user was promised.
--
-- 'agent' turns are therefore real turns, not a special case: they consolidate, they
-- order by sequence, and they appear in the transcript where they happened. The
-- column exists because the *distinction* still matters to a reader — a turn nobody
-- asked for needs to say so — and because `request_text` is empty for one, which
-- would otherwise be indistinguishable from a user sending nothing.
--
-- No default-less migration: existing rows are all user turns by construction.
ALTER TABLE turns ADD COLUMN origin TEXT NOT NULL DEFAULT 'user'
  CHECK (origin IN ('user', 'agent'));
