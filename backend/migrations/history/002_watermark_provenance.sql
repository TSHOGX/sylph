-- What confirmed a watermark, and which version of the source it confirmed.
--
-- The bare `(authority, confirmed_seq)` pair could not answer two questions a
-- retention pass has to ask.
--
-- **Which archived session confirmed this?** The Sylph id and the archive id are
-- disjoint spaces (`<agent>:<native-id>`), so a watermark recording only the Sylph
-- id leaves no way to check a confirmation against its source later. It is also
-- what made the original defect invisible: an authority comparing the two spaces
-- confirmed nothing, and an empty `watermarks` table looks identical to a
-- correctly conservative one.
--
-- **Has the downstream copy advanced since the last pass?** `source_fingerprint`
-- is TraceDB's own `file-v2:<sha256>:<bytes>:<mtime_ns>` over the agent-native
-- file, and it is the value TraceDB itself compares to decide whether to re-ingest
-- at all (`parsers::file_fingerprint`). Recording it makes re-ingestion observable:
-- a pass where every session's fingerprint is unchanged means the archive is not
-- advancing, which is what a stopped ingestion daemon looks like and is otherwise
-- indistinguishable from a healthy steady state.
--
-- Not an optimization, and deliberately not described as one: the current
-- fingerprint arrives in the same `show` response that carries the coverage bound,
-- so it cannot gate the call that fetches it.
--
-- Chosen over `ingestedAtMs` because it is content-addressed rather than a clock
-- reading — it identifies *which version* was ingested rather than when a scan ran
-- — and because it arrives on the `show` call retention already makes.
-- `ingestedAtMs` appears only on `list`, which cannot filter by id.
--
-- Both are nullable because a terminal session has neither: no archived
-- counterpart to name, and no ingested source to fingerprint.

ALTER TABLE watermarks ADD COLUMN archive_id TEXT;
ALTER TABLE watermarks ADD COLUMN source_fingerprint TEXT;
